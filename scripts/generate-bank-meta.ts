// Writes src/data/bankMeta.generated.ts: per-subject question counts, the
// ID offset each subject's questions start at, and each subject's system
// list. That's everything the main app needs to render before any question
// data has loaded (subject sidebar counts, filter chips, the full ID range
// for study shuffling) -- the questions themselves arrive per subject, as
// separate chunks, via src/data/bank.ts.
//
// Runs automatically before `npm run dev` and `npm run build`. The output
// is committed so a fresh checkout type-checks without running it first.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SUBJECT_BANKS, SUBJECTS, QUESTIONS } from "../src/data";

const counts: Record<string, number> = {};
const offsets: Record<string, number> = {};
const systems: Record<string, string[]> = {};

let offset = 0;
SUBJECT_BANKS.forEach((bank, i) => {
  const subject = bank[0]?.subject;
  if (!subject) throw new Error(`Subject bank #${i} is empty or has no subject`);
  if (SUBJECTS[i] !== subject) {
    throw new Error(`SUBJECT_BANKS[${i}] is "${subject}" but SUBJECTS[${i}] is "${SUBJECTS[i]}" -- keep both in the same order`);
  }
  counts[subject] = bank.length;
  offsets[subject] = offset;
  systems[subject] = ["All", ...Array.from(new Set(bank.map((q) => q.system)))];
  offset += bank.length;
});

if (offset !== QUESTIONS.length) throw new Error("Subject counts don't add up to the full bank");

const out = `// AUTO-GENERATED by scripts/generate-bank-meta.ts -- do not edit by hand.
// Regenerated on every \`npm run dev\` / \`npm run build\`.

export const TOTAL_QUESTIONS = ${offset};

export const SUBJECT_COUNTS: Record<string, number> = ${JSON.stringify(counts, null, 2)};

// Question IDs for subject S are SUBJECT_ID_OFFSETS[S] + 1 ... + SUBJECT_COUNTS[S].
export const SUBJECT_ID_OFFSETS: Record<string, number> = ${JSON.stringify(offsets, null, 2)};

export const SYSTEMS_BY_SUBJECT: Record<string, string[]> = ${JSON.stringify(systems, null, 2)};
`;

const target = fileURLToPath(new URL("../src/data/bankMeta.generated.ts", import.meta.url));
writeFileSync(target, out);
console.log(`bank meta: ${offset} questions across ${SUBJECT_BANKS.length} subjects`);
